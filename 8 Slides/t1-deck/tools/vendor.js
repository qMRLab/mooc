#!/usr/bin/env node
// Copies pinned library builds from npm into vendor/ (committed, so the deck needs no network).
// Run with `npm run vendor` only when upgrading a library.
'use strict';
const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const WORK = path.join(ROOT, '.cache', 'vendor');
const VENDOR = path.join(ROOT, 'vendor');

// plotly.js 2.35.2 is the version the book itself loads to render these figures.
const PACKAGES = [
  {
    spec: 'reveal.js@5.2.1',
    copy: {
      'dist/reset.css': 'reveal/reset.css',
      'dist/reveal.css': 'reveal/reveal.css',
      'dist/reveal.js': 'reveal/reveal.js',
      'plugin/notes/notes.js': 'reveal/plugin/notes.js',
      LICENSE: 'reveal/LICENSE',
    },
  },
  {
    spec: 'katex@0.16.11',
    copy: {
      'dist/katex.min.css': 'katex/katex.min.css',
      'dist/katex.min.js': 'katex/katex.min.js',
      'dist/contrib/auto-render.min.js': 'katex/auto-render.min.js',
      LICENSE: 'katex/LICENSE',
    },
    woff2: { from: 'dist/fonts', to: 'katex/fonts' },
  },
  {
    spec: 'plotly.js-cartesian-dist-min@2.35.2',
    copy: {
      'plotly-cartesian.min.js': 'plotly/plotly-cartesian.min.js',
      LICENSE: 'plotly/LICENSE',
    },
  },
];

function copyFile(from, to) {
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(from, to);
}

fs.rmSync(WORK, { recursive: true, force: true });
fs.mkdirSync(WORK, { recursive: true });
fs.rmSync(VENDOR, { recursive: true, force: true });

const lines = ['# Vendored libraries', '', 'Generated by `npm run vendor` (tools/vendor.js). Do not edit by hand.', ''];
for (const pkg of PACKAGES) {
  const packed = JSON.parse(execFileSync('npm', ['pack', pkg.spec, '--json', '--pack-destination', WORK], { encoding: 'utf8' }));
  const dir = path.join(WORK, pkg.spec.replace(/[@/]/g, '_'));
  fs.mkdirSync(dir);
  execFileSync('tar', ['-xzf', path.join(WORK, packed[0].filename), '-C', dir]);
  const src = path.join(dir, 'package');
  for (const [from, to] of Object.entries(pkg.copy)) {
    const file = path.join(src, from);
    if (!fs.existsSync(file)) {
      if (from === 'LICENSE') continue;
      throw new Error(`${pkg.spec}: ${from} not found`);
    }
    copyFile(file, path.join(VENDOR, to));
  }
  if (pkg.woff2) {
    const fontDir = path.join(src, pkg.woff2.from);
    for (const f of fs.readdirSync(fontDir)) {
      if (f.endsWith('.woff2')) copyFile(path.join(fontDir, f), path.join(VENDOR, pkg.woff2.to, f));
    }
  }
  lines.push(`- ${pkg.spec}`);
}
fs.writeFileSync(path.join(VENDOR, 'VERSIONS.md'), lines.join('\n') + '\n');
console.log('vendor/ updated');
