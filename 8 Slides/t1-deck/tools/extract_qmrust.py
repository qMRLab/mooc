#!/usr/bin/env python3
"""Copy the qmrust WebAssembly engine out of the qmrust T1 figures page into vendor/qmrust/.

The page (built in the mooc-rust project) inlines the wasm-bindgen glue (--target no-modules)
and the .wasm binary as base64, so both load from classic <script> tags and work from file://.
This copies those two pieces unchanged and records where they came from in vendor/qmrust/SOURCE.md.

Usage (from the t1-deck folder):
    python3 -I tools/extract_qmrust.py [path/to/figures-t1-chapter-qmrust.html]
"""
import hashlib
import re
import sys
from datetime import date
from pathlib import Path

DECK = Path(__file__).resolve().parents[1]
OUT = DECK / "vendor" / "qmrust"
DEFAULT_SOURCE = Path.home() / "neuropoly/projects/mooc-rust/figures-t1-chapter-qmrust.html"
GLUE_MARK = "/* ---- qmrust-wasm bindgen glue (wasm-bindgen --target no-modules) ---- */"


def scripts(html):
    return re.findall(r"<script>\n(.*?)</script>", html, flags=re.S)


def main():
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SOURCE
    html = source.read_text(encoding="utf-8")
    blocks = scripts(html)
    glue = [b for b in blocks if b.startswith(GLUE_MARK)]
    b64 = [m for b in blocks for m in re.findall(r'^var QMRUST_WASM_B64 = "[A-Za-z0-9+/=]+";$', b, flags=re.M)]
    if len(glue) != 1 or len(b64) != 1:
        sys.exit(f"expected one glue block and one QMRUST_WASM_B64 line in {source}; found {len(glue)} and {len(b64)}")
    if "let wasm_bindgen = (function(exports)" not in glue[0]:
        sys.exit("the glue block is not wasm-bindgen --target no-modules output")

    OUT.mkdir(parents=True, exist_ok=True)
    # `let` would keep wasm_bindgen out of window; scripts that look it up as a global need `var`.
    glue_js = glue[0].replace("let wasm_bindgen = (function(exports)", "var wasm_bindgen = (function(exports)", 1)
    files = {"qmrust_wasm.js": glue_js, "qmrust_wasm_b64.js": b64[0] + "\n"}
    for name, text in files.items():
        (OUT / name).write_text(text, encoding="utf-8")

    sha = lambda data: hashlib.sha256(data).hexdigest()
    (OUT / "SOURCE.md").write_text(
        "# qmrust (Rust/WebAssembly port of qMRLab)\n\n"
        "Generated by `tools/extract_qmrust.py`. Do not edit by hand.\n\n"
        f"- Copied from: `{source.name}` (mooc-rust project) on {date.today().isoformat()}\n"
        f"- Source page sha256: `{sha(source.read_bytes())}`\n"
        f"- qmrust_wasm.js sha256: `{sha((OUT / 'qmrust_wasm.js').read_bytes())}`\n"
        f"- qmrust_wasm_b64.js sha256: `{sha((OUT / 'qmrust_wasm_b64.js').read_bytes())}`\n\n"
        "The glue is copied unchanged except `let wasm_bindgen` → `var wasm_bindgen`, so the engine is a window global.\n"
        "The Rust source for parts of this build (the `long_tr_lm` fit, `signal_mean`/`signal_std` in `sim`) is not yet\n"
        "committed to qMRLab/qmrust (it is on branch `mb/dims` in the mooc-rust project's qmrust clone).\n",
        encoding="utf-8",
    )
    for name in files:
        print(f"wrote vendor/qmrust/{name} ({(OUT / name).stat().st_size / 1e6:.2f} MB)")


if __name__ == "__main__":
    main()
